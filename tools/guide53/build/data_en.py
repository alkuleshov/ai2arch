# Same toolset normalization as data.py: DeepSeek and QGIS are core;
# QuickOSM is extended; the Overpass entry is merged into QuickOSM.
def _normalize(w):
    n, sec, title, sub, desc, osn, ext, courses, prompt = w
    osn = list(osn) if osn else []
    new_ext = []
    for t in ext:
        if t == "DeepSeek":
            osn.append("DeepSeek")
        elif t == "QGIS":
            osn.insert(0, "QGIS")
        elif t == "QGIS + QuickOSM":
            osn.insert(0, "QGIS"); new_ext.append("QuickOSM")
        elif t == "Overpass":
            continue
        else:
            new_ext.append(t)
    return (n, sec, title, sub, desc, osn or None, new_ext, courses, prompt)

W = [_normalize(w) for w in W]
